"""One command, every metric: python -m evals.run_all

Reads the gold sets in data/gold/ (format in data/gold/README.md), runs what
it can with the credentials available, and writes evals/results.md. A metric
whose gold set or credentials are missing is reported as not measured -
never estimated, never left out.
"""
from __future__ import annotations

import csv
import json
import os
from pathlib import Path

from evals.metrics import ablation_table, citation_support_rate, precision_at_k, top1_accuracy

ROOT = Path(__file__).resolve().parents[1]
GOLD = ROOT / "data" / "gold"
OUT = ROOT / "evals" / "results.md"


def _jsonl(name: str) -> list[dict] | None:
    path = GOLD / name
    if not path.exists():
        return None
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def _fmt(x: float | None) -> str:
    return "—" if x is None else f"{x:.3f}"


def normalization_section() -> str:
    """Needs no Nebius key: RxNorm is a free public service."""
    rows = _jsonl("normalization.jsonl")
    if rows is None:
        return "**Normalisation top-1:** not measured — `data/gold/normalization.jsonl` is not labelled yet."
    from tessera.normalize import normalize_drugs
    from tessera.schemas import DrugRecord

    with (ROOT / "data" / "formulary.csv").open(encoding="utf-8") as fh:
        formulary = {r["rxcui"] for r in csv.DictReader(fh)}
    drugs = normalize_drugs([DrugRecord(raw_name=r["raw_text"]) for r in rows], formulary)
    preds = {r["id"]: d.rxcui for r, d in zip(rows, drugs)}
    m = top1_accuracy(preds, {r["id"]: r["rxcui"] for r in rows})
    return (f"**Normalisation top-1** (n={m['n']}): accuracy when answered "
            f"{_fmt(m['accuracy_when_answered'])}, overall {_fmt(m['accuracy_overall'])}, "
            f"coverage {_fmt(m['coverage'])} ({m['abstained']} abstained).")


def severity_section(live: bool) -> str:
    rows = _jsonl("severity.jsonl")
    if rows is None:
        return "**Severity precision@5:** not measured — `data/gold/severity.jsonl` is not labelled yet."
    if not live:
        return "**Severity precision@5:** not measured — needs `NEBIUS_API_KEY` and the built corpus."
    from tessera.cli import _load_corpus
    from tessera.config import get_settings
    from tessera.pipeline import assess
    from tessera.router import Router
    from tessera.schemas import CodeSet

    index, table, _, covered = _load_corpus(get_settings())
    router = Router()
    scores = []
    for r in rows:
        result = assess(CodeSet(codes=sorted(r["codes"])), index, table, router, covered or None)
        ranked = [(x.subject, x.object) for x in result.risks]
        p = precision_at_k(ranked, {tuple(p) for p in r["relevant"]})
        if p is not None:
            scores.append(p)
    mean = sum(scores) / len(scores) if scores else None
    return f"**Severity precision@5** (n={len(scores)} sets with any risk): {_fmt(mean)}."


def citation_section() -> str:
    rows = _jsonl("citations.jsonl")
    if rows is None:
        return "**Citation support:** not measured — `data/gold/citations.jsonl` is not labelled yet."
    rate = citation_support_rate([bool(r["supported"]) for r in rows])
    return f"**Citation support** (n={len(rows)}, human-labelled): {_fmt(rate)}."


def ablation_section() -> str:
    db = ROOT / "data" / "telemetry.sqlite"
    if not db.exists():
        return "**Router ablation:** no telemetry recorded yet — no live model calls have been made."
    from tessera.telemetry import Telemetry
    return "**Router ablation** (all recorded calls):\n\n" + ablation_table(Telemetry(db).all())


def main() -> None:
    live = bool(os.environ.get("NEBIUS_API_KEY")) or (ROOT / ".env").exists()
    body = "\n\n".join([
        "# Tessera — measured results",
        "Generated by `python -m evals.run_all`. Anything not measured says so.",
        normalization_section(), severity_section(live), citation_section(), ablation_section(),
    ])
    OUT.write_text(body + "\n", encoding="utf-8")
    print(body)


if __name__ == "__main__":
    main()
